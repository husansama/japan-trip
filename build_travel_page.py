def build_data() -> dict[str, object]:
    wb = load_workbook(WORKBOOK, read_only=True, data_only=True)
    overview = read_sheet(wb, "12天总览")
    daily_food = read_sheet(wb, "每日吃法")
    food_map = read_sheet(wb, "美食推荐")
    lodging = read_sheet(wb, "住宿区域推荐")
    alternatives = read_sheet(wb, "P人备选方案")
    transport = read_sheet(wb, "交通预约")
    checklist = read_sheet(wb, "行前清单")
    daily_detail = read_sheet(wb, "关西加强每日攻略")

    for item in food_map:
        key = (item.get("区域", ""), item.get("类型", ""))
        item["地图店铺"] = FOOD_LOCATIONS.get(key, [])
    food_map.extend(EXTRA_FOOD_RECOMMENDATIONS)
    food_map.extend(ROUTE_FOOD_ADDITIONS)
    for item in food_map:
        item["适合日期"] = FOOD_DAY_REMAP.get(item.get("适合日期", ""), item.get("适合日期", ""))
    # 旧工作簿含已取消的东京自由日、镰仓与10月6日条目；不让它们混入本次实际动线的选择列表。
    food_map = [item for item in food_map if item.get("适合日期") != "不在本次行程"]
    for item in lodging:
        # 大阪住宿已经落定，页面直接展示已订酒店与据此优化后的交通，不再保留“梅田优先”的旧建议。
        if item.get("阶段") == "大阪段":
            item.update(
                {
                    "首选区域": "已预订：南船场／长堀桥／心斋桥",
                    "备选区域": "无需备选",
                    "为什么": "酒店靠近长堀桥与心斋桥：晚间步行覆盖心斋桥、道顿堀；白天分别接地铁和大阪站前往大阪城、姬路神户及USJ。",
                    "适合酒店关键词": "Sugata Hotel Osaka Shinsaibashi, Series by Marriott",
                    "导游建议": "把道顿堀集中在9月26日晚；9月25日18:05落地后只入住和就近晚餐。",
                }
            )
        item["住宿推荐"] = HOTEL_RECOMMENDATIONS.get(item.get("阶段", ""), [])

    foods_by_day = {item.get("日期", ""): item for item in daily_food}
    details_by_date: dict[str, list[dict[str, str]]] = {}
    for item in daily_detail:
        details_by_date.setdefault(item.get("日期", ""), []).append(item)

    days = []
    for item in overview:
        date = item.get("日期", "")
        short_date = date[5:] if len(date) >= 10 else date
        day_id = item.get("天数", "")
        # 返程改至10月5日，原工作簿中的10月6日不再属于本次实际行程，网页不保留空白返程日。
        if day_id == "Day12":
            continue
        food = {
            **foods_by_day.get(short_date, {}),
            **DAY_FOOD_OVERRIDES.get(day_id, {}),
        }
        # 住宿和日期核对后的覆盖项优先于Excel原稿；未覆盖字段仍由Excel维护。
        days.append(
            {
                **item,
                **DAY_OVERRIDES.get(day_id, {}),
                "短日期": short_date,
                "吃法": food,
                "细节": DAY_DETAIL_OVERRIDES.get(day_id, details_by_date.get(short_date, [])),
                "景点详解": DAY_ATTRACTION_GUIDES.get(day_id, []),
                "票券安排": PASS_USE_PLANS.get(day_id, []),
                "交通分段": SEGMENT_ROUTES.get(day_id, []),
            }
        )

    return {
        "trip": {
            "title": "日本11天10晚",
            "subtitle": "香港出发 · 关西深游 · 东京两晚后经羽田与北京返穗",
            "dates": "2026.09.25 - 2026.10.05",
            "route": "大阪4晚 → 京都4晚 → 东京2晚 → 羽田/北京/广州",
        },
        "days": days,
        "foodMap": food_map,
        "coupleFoodGuide": COUPLE_FOOD_GUIDE,
        "foodVisuals": FOOD_VISUALS,
        "lodging": lodging,
        "alternatives": alternatives,
        "transport": transport,
        "checklist": checklist,
        "usj": USJ_GUIDE,
        "updatedAt": "2026-08-20",
    }


